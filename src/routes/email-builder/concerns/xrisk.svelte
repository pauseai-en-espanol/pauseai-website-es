<p>
	En resumen: no sabemos cómo alinear la IA con los objetivos y valores complejos que tenemos los
	humanos. Cuando se materialice un sistema superinteligente, existe un riesgo significativo de que
	una de estas instancias persiga un objetivo desalineado sin que podamos detenerlo. E incluso si
	esa IA sobrehumana permaneciera bajo control humano, quien ostentara tal poder podría usarlo para
	cambiar el mundo de forma drástica e irreversible. Tal IA podría usarse para desarrollar nuevas
	tecnologías y armas, manipular a masas de personas o derrocar gobiernos.
